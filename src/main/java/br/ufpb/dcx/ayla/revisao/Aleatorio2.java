package br.ufpb.dcx.ayla.revisao;

public class Aleatorio2 {
    public static void main(String [] args){
        int k=0;
        while(k<3){
            System.out.println("Oi "+k);
            k++;
        }

        for (int i=0; i<3; i++){
            System.out.println("Tchau "+i);
        }

        int j = 0;
        do {
            System.out.println("Beleza "+j);
            j++;
        } while(j<3);

    }
}
